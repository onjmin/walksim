#!/usr/bin/env bash
# 作者の線画 → Qwen-Image-Edit（192.168.0.19）で清書＋べた塗り
# 作業フォルダ（線画を白地にした *_white.png を置き、清書 *_ai.png を受ける）
S="${WORK:-$(pwd)/work}"
# ComfyUI の agent/edit.py（接続先は COMFY_URL。既定 192.168.0.19:8188 の 16GB 機）
cd "${COMFY_DIR:-C:/_own/git/ComfyUI}"
COMMON="この線画のキャラクターを、同じポーズ・同じ髪型・同じ服・同じ表情のまま清書して、アニメ塗りのべた塗りで色を付けてください。線は太めの1本線ではっきり、影は1段だけ。背景は真っ白で、床の影や地面は描かない。"
gen() {
	venv/Scripts/python.exe agent/edit.py --image "$S/$1_white.png" --prompt "$COMMON $2" --out "$S/$1_ai.png" --seed "${3:-7}" 2>&1 | tail -1
}
